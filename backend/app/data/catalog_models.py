"""Curated product models with structured specifications.

Listings from retailers describe a product in their own words; this registry
says what the product is. Each entry is one model line as the normaliser names
it ("iphone17", "galaxys25ultra"), with the sizes and colours the maker sells
and the headline specifications. Listings attach to an entry by line, so the
family page can list every official size even before a store has been seen
for it, and the category page can filter by RAM, storage and screen size.

Specifications are entered by BuyWise from manufacturer pages and are shown as
such: `verified_on` records when an entry was last checked. Nothing in this
file is a price. Prices come only from live retailer offers.
"""

from __future__ import annotations

SPECS_NOTE = "Specifications curated by BuyWise from manufacturer pages; confirm with the maker before buying."


def _m(
    line,
    label,
    brand,
    released,
    *,
    display_in,
    refresh_hz,
    chip,
    ram_gb,
    storage_gb,
    camera_mp,
    battery_mah,
    colors,
    os="Android",
    verified_on="2026-09-22",
    category="phones",
):
    return {
        "line": line,
        "label": label,
        "brand": brand,
        "category": category,
        "released": released,
        "specs": {
            "display_in": display_in,
            "refresh_hz": refresh_hz,
            "chip": chip,
            "ram_gb": list(ram_gb) if ram_gb else [],
            "storage_gb": list(storage_gb),
            "main_camera_mp": camera_mp,
            "battery_mah": battery_mah,
            "os": os,
            "five_g": True,
        },
        "colors": list(colors),
        "verified_on": verified_on,
    }


