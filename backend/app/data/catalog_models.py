_BY_LINE = {m["line"]: m for m in CATALOG_MODELS}
CATEGORIES = {"phones": "Phones"}


def catalog_model(line: str | None) -> dict | None:
    return _BY_LINE.get(line or "")


def models_for_category(category: str) -> list[dict]:
    return [m for m in CATALOG_MODELS if m["category"] == category]


def storage_label(gb: int) -> str:
    return f"{gb // 1024}TB" if gb >= 1024 and gb % 1024 == 0 else f"{gb}GB"
